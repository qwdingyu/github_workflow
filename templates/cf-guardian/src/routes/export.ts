// Report Export Routes — generate downloadable SEO+GEO reports
import { Hono } from "hono";
import type { Env } from "../index";
import { SCAN_QUERIES, GEO_QUERIES } from "../db/schema";
import { checkRobotsTxt } from "../services/robots-checker";
import { auditSecurityHeaders } from "../services/security-checker";

const exportApp = new Hono<{ Bindings: Env }>();

interface User { id: string; email: string; plan: string; token: string; }

async function getUser(c: any): Promise<User | null> {
  const token = c.req.header("x-auth-token");
  if (!token) return null;
  const row = await c.env.DB.prepare("SELECT * FROM users WHERE token = ?")
    .bind(token)
    .first();
  return (row as User) || null;
}

async function verifySite(c: any, siteId: string, userId: string) {
  const site = await c.env.DB.prepare(
    "SELECT * FROM sites WHERE id = ? AND user_id = ?"
  ).bind(siteId, userId).first();
  return site || null;
}

// ─── GET /api/export/:siteId/report — Full text-based report ──────────────

exportApp.get("/:siteId/report", async (c) => {
  const user = await getUser(c);
  if (!user) return c.json({ error: "Unauthorized" }, 401);

  const siteId = c.req.param("siteId");
  const site = await verifySite(c, siteId, user.id);
  if (!site) return c.json({ error: "Site not found" }, 404);

  // Get latest scan
  const scan = await c.env.DB.prepare(SCAN_QUERIES.GET_LATEST)
    .bind(siteId)
    .first();
  if (!scan) return c.json({ error: "No scan results yet" }, 404);

  const s = scan as any;
  let issues: any[] = [];
  if (s.issues_json) {
    try { issues = JSON.parse(s.issues_json); } catch {}
  }

  // GEO checks
  const { results: geoChecks } = await c.env.DB.prepare(GEO_QUERIES.LIST_BY_SCAN)
    .bind(s.id)
    .all();
  const geoChecksParsed = (geoChecks || []).map((g: any) => {
    let details;
    try { details = JSON.parse(g.details_json); } catch { details = {}; }
    return { type: g.check_type, status: g.status, score: g.score, details };
  });

  // Run live checks for report freshness
  const robotsResult = await checkRobotsTxt(site.url as string);
  const securityResult = await auditSecurityHeaders(site.url as string);

  // Build report text
  const now = new Date().toISOString().split("T")[0];
  const lines: string[] = [];

  lines.push("=" .repeat(70));
  lines.push("SEO + GEO AUDIT REPORT");
  lines.push(`Site: ${site.url}`);
  lines.push(`Date: ${now}`);
  lines.push(`Generated by: SEO Guardian`);
  lines.push("=" .repeat(70));
  lines.push("");

  // Executive Summary
  lines.push("EXECUTIVE SUMMARY");
  lines.push("-".repeat(40));
  lines.push(`SEO Score:    ${s.score}/100`);
  lines.push(`GEO Score:    ${s.geo_score || 0}/100 (${s.geo_band || "N/A"})`);
  lines.push(`Security:     ${securityResult.grade} (${securityResult.score}/100)`);
  lines.push(`Robots.txt:   ${robotsResult.found ? "Found (" + robotsResult.score + "/100)" : "Not found"}`);
  lines.push(`Total Issues: ${issues.length} (Critical: ${issues.filter((i: any) => i.severity === "critical").length})`);
  lines.push("");

  // SEO Details
  lines.push("SEO ANALYSIS");
  lines.push("-".repeat(40));
  lines.push(`Title:        "${s.title || "MISSING"}" (${s.title_length || 0} chars)`);
  lines.push(`Meta Desc:    "${s.meta_description ? s.meta_description.substring(0, 80) + "..." : "MISSING"}" (${s.meta_description_length || 0} chars)`);
  lines.push(`H1 Count:     ${s.h1_count}`);
  lines.push(`H2 Count:     ${s.h2_count}`);
  lines.push(`Images:       ${s.image_count} total, ${s.image_missing_alt} missing alt`);
  lines.push(`Canonical:    ${s.has_canonical ? "Yes" : "No"}`);
  lines.push(`Schema:       ${s.has_schema ? "Yes" : "No"}`);
  lines.push(`HTTPS:        ${s.is_https ? "Yes" : "No"}`);
  lines.push("");

  // Issues
  if (issues.length > 0) {
    lines.push("ISSUES FOUND");
    lines.push("-".repeat(40));
    for (const issue of issues) {
      lines.push(`[${issue.severity.toUpperCase()}] ${issue.title}`);
      lines.push(`  ${issue.message}`);
      lines.push("");
    }
  }

  // GEO Analysis
  lines.push("GEO (AI SEARCH) ANALYSIS");
  lines.push("-".repeat(40));
  for (const gc of geoChecksParsed) {
    const statusIcon = gc.status === "pass" ? "PASS" : gc.status === "warn" ? "WARN" : "FAIL";
    lines.push(`[${statusIcon}] ${gc.type}: ${gc.score}/100`);
  }
  lines.push("");

  // Security
  lines.push("SECURITY HEADERS");
  lines.push("-".repeat(40));
  for (const h of securityResult.headers) {
    const statusIcon = h.status === "pass" ? "PASS" : h.status === "warn" ? "WARN" : "FAIL";
    lines.push(`[${statusIcon}] ${h.name}: ${h.value || "MISSING"}`);
  }
  lines.push("");

  // Robots.txt
  lines.push("ROBOTS.TXT ANALYSIS");
  lines.push("-".repeat(40));
  lines.push(`Found: ${robotsResult.found ? "Yes" : "No"}`);
  lines.push(`Score: ${robotsResult.score}/100`);
  lines.push(`Agents: ${robotsResult.agents.join(", ") || "None specified"}`);
  lines.push(`Sitemaps: ${robotsResult.sitemaps.join(", ") || "None listed"}`);
  if (robotsResult.issues.length > 0) {
    for (const issue of robotsResult.issues) {
      lines.push(`[${issue.severity.toUpperCase()}] ${issue.title}: ${issue.message}`);
    }
  }
  lines.push("");

  // Recommendations
  lines.push("TOP RECOMMENDATIONS");
  lines.push("-".repeat(40));
  const criticalIssues = issues.filter((i: any) => i.severity === "critical");
  const warningIssues = issues.filter((i: any) => i.severity === "warning");
  const topIssues = [...criticalIssues, ...warningIssues].slice(0, 10);
  topIssues.forEach((issue: any, idx: number) => {
    lines.push(`${idx + 1}. [${issue.severity.toUpperCase()}] ${issue.title}`);
    lines.push(`   ${issue.message}`);
  });
  lines.push("");

  lines.push("=" .repeat(70));
  lines.push(`Report generated by SEO Guardian on ${now}`);
  lines.push("Powered by Cloudflare Workers + AI");
  lines.push("=" .repeat(70));

  const reportText = lines.join("\n");

  return new Response(reportText, {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Content-Disposition": `attachment; filename="seo-guardian-report-${site.url?.replace(/[^a-zA-Z0-9]/g, "-")}-${now}.txt"`,
    },
  });
});

// ─── GET /api/export/:siteId/json — Machine-readable JSON report ──────────

exportApp.get("/:siteId/json", async (c) => {
  const user = await getUser(c);
  if (!user) return c.json({ error: "Unauthorized" }, 401);

  const siteId = c.req.param("siteId");
  const site = await verifySite(c, siteId, user.id);
  if (!site) return c.json({ error: "Site not found" }, 404);

  const scan = await c.env.DB.prepare(SCAN_QUERIES.GET_LATEST)
    .bind(siteId)
    .first();
  if (!scan) return c.json({ error: "No scan results yet" }, 404);

  const s = scan as any;
  let issues: any[] = [];
  if (s.issues_json) {
    try { issues = JSON.parse(s.issues_json); } catch {}
  }

  const { results: geoChecks } = await c.env.DB.prepare(GEO_QUERIES.LIST_BY_SCAN)
    .bind(s.id)
    .all();

  const robotsResult = await checkRobotsTxt(site.url as string);
  const securityResult = await auditSecurityHeaders(site.url as string);

  return new Response(JSON.stringify({
    metadata: {
      generatedAt: new Date().toISOString(),
      site: { id: site.id, url: site.url, name: site.name },
      scanId: s.id,
      scannedAt: s.scanned_at,
      version: "1.0",
    },
    scores: {
      seo: s.score,
      geo: s.geo_score || 0,
      geoBand: s.geo_band || "",
      security: securityResult.score,
      securityGrade: securityResult.grade,
      robots: robotsResult.score,
    },
    seo: {
      title: s.title,
      titleLength: s.title_length,
      metaDescription: s.meta_description,
      metaDescriptionLength: s.meta_description_length,
      h1Count: s.h1_count,
      h2Count: s.h2_count,
      imageCount: s.image_count,
      imageMissingAlt: s.image_missing_alt,
      hasCanonical: !!s.has_canonical,
      hasSchema: !!s.has_schema,
      isHttps: !!s.is_https,
    },
    issues,
    geo: (geoChecks || []).map((g: any) => ({
      type: g.check_type,
      status: g.status,
      score: g.score,
    })),
    security: {
      headers: securityResult.headers,
      issues: securityResult.issues,
    },
    robots: {
      found: robotsResult.found,
      score: robotsResult.score,
      agents: robotsResult.agents,
      sitemaps: robotsResult.sitemaps,
      issues: robotsResult.issues,
    },
  }, null, 2), {
    headers: {
      "Content-Type": "application/json",
      "Content-Disposition": `attachment; filename="seo-guardian-report-${site.url?.replace(/[^a-zA-Z0-9]/g, "-")}-${new Date().toISOString().split("T")[0]}.json"`,
    },
  });
});

export { exportApp as exportRoutes };
