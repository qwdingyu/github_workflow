// Sitemap Generator Service — generates XML sitemaps from crawled pages

export interface SitemapUrl {
  loc: string;
  lastmod?: string;
  changefreq?: "always" | "hourly" | "daily" | "weekly" | "monthly" | "yearly" | "never";
  priority?: number; // 0.0 - 1.0
}

export interface SitemapIndex {
  sitemapUrls: SitemapUrl[];
  xml: string;
  totalUrls: number;
}

/**
 * Generate an XML sitemap from crawled pages.
 * Follows sitemaps.org protocol.
 */
export function generateSitemapXml(urls: SitemapUrl[], hostname: string): string {
  const urlEntries = urls.map((u) => {
    const lastmod = u.lastmod ? `<lastmod>${u.lastmod}</lastmod>` : "";
    const changefreq = u.changefreq ? `<changefreq>${u.changefreq}</changefreq>` : "";
    const priority = u.priority !== undefined ? `<priority>${u.priority.toFixed(1)}</priority>` : "";
    return `  <url>
    <loc>${escapeXml(u.loc)}</loc>
    ${lastmod}
    ${changefreq}
    ${priority}
  </url>`;
  }).join("\n");

  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urlEntries}
</urlset>`;
}

/**
 * Generate a sitemap index for large sites with multiple sitemplits.
 */
export function generateSitemapIndexXml(sitemapUrls: string[]): string {
  const entries = sitemapUrls.map((url) => `  <sitemap>
    <loc>${escapeXml(url)}</loc>
  </sitemap>`).join("\n");

  return `<?xml version="1.0" encoding="UTF-8"?>
<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries}
</sitemapindex>`;
}

/**
 * Create a recommended sitemap for a site based on crawled pages.
 */
export async function createRecommendedSitemap(
  url: string,
  maxPages: number = 50,
): Promise<SitemapIndex> {
  // Use a simple fetch approach since we don't have env here
  const resp = await fetch(url, { cf: { scrapeShield: false } });
  const html = await resp.text();
  const parser = new (globalThis as any).DOMParser();
  const doc = parser.parseFromString(html, "text/html");
  const links = doc.querySelectorAll("a[href]");

  const sitemapUrls: SitemapUrl[] = [];
  const seen = new Set<string>();
  const base = new URL(url);

  // Add homepage
  sitemapUrls.push({
    loc: base.origin,
    changefreq: "daily",
    priority: 1.0,
  });
  seen.add(base.origin);

  // Add internal links
  for (const link of links) {
    const href = link.getAttribute("href") || "";
    if (!href || href.startsWith("#") || href.startsWith("javascript:")) continue;
    try {
      const absolute = new URL(href, url);
      if (absolute.hostname !== base.hostname) continue;
      const cleanUrl = absolute.href.split("#")[0];
      if (seen.has(cleanUrl)) continue;
      seen.add(cleanUrl);
      if (seen.size > maxPages + 1) break;

      const path = absolute.pathname.toLowerCase();
      let changefreq: SitemapUrl["changefreq"] = "monthly";
      if (path.includes("/blog/") || path.includes("/news/")) changefreq = "daily";
      else if (path.includes("/product/") || path.includes("/shop/")) changefreq = "weekly";
      else if (path.includes("/category/") || path.includes("/tag/")) changefreq = "weekly";

      sitemapUrls.push({
        loc: cleanUrl,
        changefreq,
        priority: Math.max(0.3, 0.8 - (seen.size - 1) * 0.02),
      });
    } catch {
      continue;
    }
  }

  const xml = generateSitemapXml(sitemapUrls, new URL(url).hostname);

  return {
    sitemapUrls,
    xml,
    totalUrls: sitemapUrls.length,
  };
}

